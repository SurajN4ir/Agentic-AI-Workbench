"""
app/artifacts/generator.py
==========================
Generates professional deliverables (Word .docx, Excel .xlsx, and Markdown)
strictly bounded inside session-scoped workspace directories.
"""

import logging
from pathlib import Path

import docx
import openpyxl
from docx.shared import Inches, Pt, RGBColor
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from app.artifacts.models import ReportSpec, SpreadsheetSpec, TableBlock, TextBlock
from app.tools.interface import validate_workspace_path

logger = logging.getLogger("sovereign.artifacts.generator")


class ArtifactGenerator:
    """Creates formatted Word, Excel, and Markdown documents inside validated workspace paths."""

    @staticmethod
    def generate_docx(spec: ReportSpec, session_id: str) -> Path:
        """Generates a professional Word document from a ReportSpec."""
        filename = spec.filename
        if not filename.lower().endswith(".docx"):
            filename = f"{filename}.docx"

        target_path = validate_workspace_path(filename, session_id, create_parents=True)
        doc = docx.Document()

        # Page margins: 1 inch
        for section in doc.sections:
            section.top_margin = Inches(1)
            section.bottom_margin = Inches(1)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

        # Title
        title_p = doc.add_paragraph()
        title_run = title_p.add_run(spec.title)
        title_run.font.size = Pt(22)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(15, 23, 42)  # Slate 900
        title_p.paragraph_format.space_after = Pt(4)

        # Subtitle
        if spec.subtitle:
            sub_p = doc.add_paragraph()
            sub_run = sub_p.add_run(spec.subtitle)
            sub_run.font.size = Pt(13)
            sub_run.font.italic = True
            sub_run.font.color.rgb = RGBColor(100, 116, 139)  # Slate 500
            sub_p.paragraph_format.space_after = Pt(8)

        # Metadata line
        meta_p = doc.add_paragraph()
        meta_run = meta_p.add_run(f"Generated by: {spec.author or 'Sovereign AI Workbench'}")
        meta_run.font.size = Pt(9)
        meta_run.font.color.rgb = RGBColor(148, 163, 184)
        meta_p.paragraph_format.space_after = Pt(18)

        # Sections
        for block in spec.sections:
            if isinstance(block, TextBlock):
                if block.heading:
                    h = doc.add_heading(level=2)
                    h_run = h.add_run(block.heading)
                    h_run.font.size = Pt(14)
                    h_run.font.bold = True
                    h_run.font.color.rgb = RGBColor(30, 41, 59)
                    h.paragraph_format.space_before = Pt(12)
                    h.paragraph_format.space_after = Pt(4)

                for line in block.body.split("\n"):
                    trimmed = line.strip()
                    if not trimmed:
                        continue
                    if trimmed.startswith(("- ", "* ", "• ")):
                        p = doc.add_paragraph(style="List Bullet")
                        p.add_run(trimmed[2:].strip())
                    else:
                        p = doc.add_paragraph()
                        p.add_run(trimmed)
                        p.paragraph_format.space_after = Pt(4)

            elif isinstance(block, TableBlock):
                if block.caption:
                    cp = doc.add_paragraph()
                    c_run = cp.add_run(f"Table: {block.caption}")
                    c_run.font.bold = True
                    c_run.font.size = Pt(10)
                    cp.paragraph_format.space_before = Pt(10)
                    cp.paragraph_format.space_after = Pt(2)

                num_cols = len(block.headers)
                table = doc.add_table(rows=1 + len(block.rows), cols=num_cols)
                table.style = "Table Grid"

                # Header Row
                hdr_cells = table.rows[0].cells
                for i, title in enumerate(block.headers):
                    hdr_cells[i].text = title
                    for p in hdr_cells[i].paragraphs:
                        for run in p.runs:
                            run.font.bold = True
                            run.font.size = Pt(10)

                # Data Rows
                for row_idx, row_data in enumerate(block.rows):
                    row_cells = table.rows[row_idx + 1].cells
                    for col_idx, cell_value in enumerate(row_data):
                        if col_idx < num_cols:
                            row_cells[col_idx].text = str(cell_value)
                            for p in row_cells[col_idx].paragraphs:
                                for run in p.runs:
                                    run.font.size = Pt(9.5)

                doc.add_paragraph().paragraph_format.space_after = Pt(8)

        doc.save(str(target_path))
        logger.info("Generated Word deliverable at %s", target_path)
        return target_path

    @staticmethod
    def generate_xlsx(spec: SpreadsheetSpec, session_id: str) -> Path:
        """Generates a styled Excel workbook with auto column widths from SpreadsheetSpec."""
        filename = spec.filename
        if not filename.lower().endswith(".xlsx"):
            filename = f"{filename}.xlsx"

        target_path = validate_workspace_path(filename, session_id, create_parents=True)
        wb = openpyxl.Workbook()
        wb.remove(wb.active)  # Remove default initial sheet  # type: ignore[arg-type]

        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid")  # Slate-800
        data_font = Font(name="Calibri", size=10)
        border_side = Side(border_style="thin", color="E2E8F0")
        thin_border = Border(left=border_side, right=border_side, top=border_side, bottom=border_side)

        for sheet_spec in spec.sheets:
            ws = wb.create_sheet(title=sheet_spec.name[:31])

            # Headers
            start_row = 1
            if sheet_spec.headers:
                ws.append(sheet_spec.headers)
                for col_num in range(1, len(sheet_spec.headers) + 1):
                    cell = ws.cell(row=1, column=col_num)
                    cell.font = header_font
                    cell.fill = header_fill
                    cell.alignment = Alignment(horizontal="center", vertical="center")
                    cell.border = thin_border
                start_row = 2

            # Data rows
            for row in sheet_spec.rows:
                ws.append(row)

            # Apply borders and formatting to data
            for row_num in range(start_row, start_row + len(sheet_spec.rows)):
                for col_num in range(1, (len(sheet_spec.headers) or (len(sheet_spec.rows[0]) if sheet_spec.rows else 1)) + 1):
                    cell = ws.cell(row=row_num, column=col_num)
                    cell.font = data_font
                    cell.border = thin_border

            # Auto-fit column widths
            for col in ws.columns:
                max_len = 0
                col_letter = get_column_letter(col[0].column)
                for cell in col:
                    val_str = str(cell.value or "")
                    if len(val_str) > max_len:
                        max_len = len(val_str)
                ws.column_dimensions[col_letter].width = max(max_len + 4, 12)

        wb.save(str(target_path))
        logger.info("Generated Excel deliverable at %s", target_path)
        return target_path

    @staticmethod
    def generate_markdown(spec: ReportSpec, session_id: str) -> Path:
        """Generates a GitHub-flavored Markdown report."""
        filename = spec.filename
        if not filename.lower().endswith((".md", ".txt")):
            filename = f"{filename}.md"

        target_path = validate_workspace_path(filename, session_id, create_parents=True)

        lines: list[str] = [
            f"# {spec.title}",
        ]
        if spec.subtitle:
            lines.append(f"*{spec.subtitle}*")
        lines.append(f"\n_Generated by {spec.author or 'Sovereign AI Workbench'}_\n---")

        for block in spec.sections:
            if isinstance(block, TextBlock):
                if block.heading:
                    lines.append(f"\n## {block.heading}")
                lines.append(f"\n{block.body}")
            elif isinstance(block, TableBlock):
                if block.caption:
                    lines.append(f"\n**Table: {block.caption}**")
                # Markdown table header
                header_line = "| " + " | ".join(block.headers) + " |"
                sep_line = "| " + " | ".join(["---"] * len(block.headers)) + " |"
                lines.append(header_line)
                lines.append(sep_line)
                for row in block.rows:
                    row_line = "| " + " | ".join(str(c) for c in row) + " |"
                    lines.append(row_line)

        content = "\n".join(lines) + "\n"
        with open(target_path, "w", encoding="utf-8") as f:
            f.write(content)

        logger.info("Generated Markdown deliverable at %s", target_path)
        return target_path
